"""Request bank concepts (work-plan E3.4, `docs/evaluating-resto.md` §5, 2026-09-23).

A concept is one hand-written English request with one gold answer; its variants (translations,
registers, vaguised forms, typos) are generated by `eval.request_bank.generate` and share that gold,
except a vaguised variant, whose gold becomes "expect an ambiguity". Times are clock times
(ADR-0028); "peak hour" is `demand_ref="peak"`. Nothing here depends on DEV-NET: ids are strings the
Parser copies, never checks.
"""

from __future__ import annotations

import zlib
from dataclasses import dataclass, replace
from enum import StrEnum

from resto.domain.value_objects.arm import Arm
from resto.domain.value_objects.intervention import Intervention, InterventionType
from resto.domain.value_objects.intervention_target import EdgeTarget, LaneTarget
from resto.domain.value_objects.question import Intent, Question
from resto.domain.value_objects.time_window import TimeWindow

LANGUAGES = {
    "en": "English",
    "ca": "Catalan",
    "es": "Spanish (Spain)",
    "de": "German",
    "zh": "Simplified Chinese",
}


class Category(StrEnum):
    SINGLE = "single"
    MULTI_ARM = "multi_arm"
    COMBINED = "combined"
    AMBIGUOUS = "ambiguous"
    UNINTELLIGIBLE = "unintelligible"
    OUT_OF_SCOPE = "out_of_scope"
    ADVERSARIAL = "adversarial"


class Style(StrEnum):
    TECHNICAL = "technical"
    COLLOQUIAL = "colloquial"
    TELEGRAPHIC = "telegraphic"
    VERBOSE = "verbose"
    MESSY = "messy"


class Vague(StrEnum):
    """The one piece of information a vaguised variant makes imprecise."""

    TIME = "time"
    VALUE = "value"
    PLACE = "place"
    GROUPING = "grouping"


class Noise(StrEnum):
    TYPOS = "typos"
    NO_ACCENTS = "no_accents"


@dataclass(frozen=True, slots=True)
class AmbiguousGold:
    """The Parser must return a non-empty `ambiguities[]`; `intent` is scored only when set."""

    reason: str
    intent: Intent | None = None


Gold = Question | AmbiguousGold


@dataclass(frozen=True, slots=True)
class VariantSpec:
    lang: str = "en"
    style: Style | None = None
    vague: Vague | None = None
    noise: Noise | None = None

    def __post_init__(self) -> None:
        if self.lang not in LANGUAGES:
            raise ValueError(f"unknown language {self.lang!r}")
        if self.lang == "en" and not (self.style or self.vague or self.noise):
            raise ValueError("the plain English variant is the concept itself")

    @property
    def key(self) -> str:
        parts = [self.lang, self.style, self.vague and f"vague_{self.vague}", self.noise]
        return "-".join(p for p in parts if p)

    @property
    def needs_llm(self) -> bool:
        return self.lang != "en" or self.style is not None or self.vague is not None


@dataclass(frozen=True, slots=True)
class Concept:
    id: str
    category: Category
    text: str
    gold: Gold
    variants: tuple[VariantSpec, ...] = ()

    def __post_init__(self) -> None:
        if isinstance(self.gold, Question) and self.gold.text != self.text:
            raise ValueError(f"{self.id}: the gold Question's text must be the concept's text")
        keys = [v.key for v in self.variants]
        if len(set(keys)) != len(keys):
            raise ValueError(f"{self.id}: duplicate variants")
        if any(v.vague for v in self.variants) and isinstance(self.gold, AmbiguousGold):
            raise ValueError(f"{self.id}: an ambiguous concept cannot be vaguised further")

    @property
    def split(self) -> str:
        """70/30 dev/held-out, by concept, stable across runs."""
        return "dev" if zlib.crc32(self.id.encode()) % 10 < 7 else "held_out"

    def variant_id(self, spec: VariantSpec) -> str:
        return f"{self.id}.{spec.key}"

    def gold_for(self, spec: VariantSpec, text: str) -> Gold:
        if spec.vague is not None:
            # Blurring together-vs-compared also blurs what kind of question it is.
            keeps_intent = isinstance(self.gold, Question) and spec.vague is not Vague.GROUPING
            intent = self.gold.intent if isinstance(self.gold, Question) and keeps_intent else None
            return AmbiguousGold(reason=f"vague {spec.vague}", intent=intent)
        if isinstance(self.gold, Question):
            return replace(self.gold, text=text)
        return self.gold


def clock(hh_mm: str) -> float:
    hours, minutes = hh_mm.split(":")
    return int(hours) * 3600.0 + int(minutes) * 60.0


def window(start: str, end: str) -> TimeWindow:
    return TimeWindow(clock(start), clock(end))


def kmh(value: float) -> float:
    return round(value / 3.6, 3)


def _q(text: str, intent: Intent, **fields: object) -> Question:
    return Question(text=text, intent=intent, **fields)  # type: ignore[arg-type]


W_0800_0830 = window("08:00", "08:30")

_R001 = (
    "On the DEV-NET network, what would happen to the mean travel time if lane 1 of edge B0C0 "
    "were closed from 08:00 to 08:30?"
)
_R002 = "During the morning peak on DEV-NET, which edges have the highest occupancy?"
_R003 = (
    "On DEV-NET, which reduces the mean delay more: closing edge C0D0 from 08:00 to 08:30, or "
    "limiting edge B2C2 to 30 km/h over the same period?"
)
_R004 = (
    "Run a simulation of DEV-NET in which lane 1 of B0C0 is closed and edge B2C2 is limited to "
    "30 km/h at the same time, both from 08:00 to 08:30, and report the mean delay."
)
_R005 = "What happens if I close B0C0 and C0D0?"

_CLOSE_B0C0_L1 = Intervention(
    InterventionType.LANE_CLOSURE, LaneTarget("B0C0", 1), window=W_0800_0830
)
_LIMIT_B2C2_30 = Intervention(
    InterventionType.SPEED_LIMIT, EdgeTarget("B2C2"), params={"speed": kmh(30)},
    window=W_0800_0830,
)
_CLOSE_C0D0 = Intervention(InterventionType.EDGE_CLOSURE, EdgeTarget("C0D0"), window=W_0800_0830)

CONCEPTS: tuple[Concept, ...] = (
    Concept(
        "R001",
        Category.SINGLE,
        _R001,
        _q(
            _R001, Intent.COUNTERFACTUAL, network_ref="DEV-NET",
            interventions=(_CLOSE_B0C0_L1,), metrics_of_interest=("mean_travel_time",),
        ),
        (
            VariantSpec("ca"),
            VariantSpec("es"),
            VariantSpec("de"),
            VariantSpec("zh"),
            VariantSpec("en", style=Style.COLLOQUIAL),
            VariantSpec("en", style=Style.TELEGRAPHIC),
            VariantSpec("es", vague=Vague.TIME),
            VariantSpec("en", noise=Noise.TYPOS),
        ),
    ),
    Concept(
        "R002",
        Category.SINGLE,
        _R002,
        _q(
            _R002, Intent.DESCRIBE, network_ref="DEV-NET", demand_ref="peak",
            metrics_of_interest=("occupancy",),
        ),
        (
            VariantSpec("ca"),
            VariantSpec("zh"),
            VariantSpec("en", style=Style.MESSY),
            VariantSpec("es", noise=Noise.NO_ACCENTS),
        ),
    ),
    Concept(
        "R003",
        Category.MULTI_ARM,
        _R003,
        _q(
            _R003, Intent.COMPARE, network_ref="DEV-NET",
            arms=(
                Arm("closure", interventions=(_CLOSE_C0D0,)),
                Arm("speed_limit", interventions=(_LIMIT_B2C2_30,)),
            ),
            metrics_of_interest=("mean_delay",),
        ),
        (
            VariantSpec("ca"),
            VariantSpec("de"),
            VariantSpec("zh"),
            VariantSpec("en", style=Style.VERBOSE),
            VariantSpec("en", vague=Vague.GROUPING),
        ),
    ),
    Concept(
        "R004",
        Category.COMBINED,
        _R004,
        _q(
            _R004, Intent.RUN, network_ref="DEV-NET",
            interventions=(_CLOSE_B0C0_L1, _LIMIT_B2C2_30), metrics_of_interest=("mean_delay",),
        ),
        (
            VariantSpec("es"),
            VariantSpec("zh"),
            VariantSpec("en", style=Style.TELEGRAPHIC),
            VariantSpec("de", noise=Noise.TYPOS),
        ),
    ),
    Concept(
        "R005",
        Category.AMBIGUOUS,
        _R005,
        AmbiguousGold("together or separately, and when", intent=None),
        (
            VariantSpec("ca"),
            VariantSpec("zh"),
            VariantSpec("en", style=Style.COLLOQUIAL),
        ),
    ),
)


def concept_by_id(concept_id: str) -> Concept:
    for concept in CONCEPTS:
        if concept.id == concept_id:
            return concept
    raise KeyError(concept_id)
