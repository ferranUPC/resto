LANGUAGES = {
    "en": "English",
    "ca": "Catalan",
    "es": "Spanish (Spain)",
    "de": "German",
    "zh": "Simplified Chinese",
}


class Category(StrEnum):
    SINGLE = "single"
    MULTI_ARM = "multi_arm"
    COMBINED = "combined"
    AMBIGUOUS = "ambiguous"
    UNINTELLIGIBLE = "unintelligible"
    OUT_OF_SCOPE = "out_of_scope"
    ADVERSARIAL = "adversarial"


class Style(StrEnum):
    TECHNICAL = "technical"
    COLLOQUIAL = "colloquial"
    TELEGRAPHIC = "telegraphic"
    VERBOSE = "verbose"
    MESSY = "messy"


class Vague(StrEnum):
    """The one piece of information a vaguised variant makes imprecise."""

    TIME = "time"
    VALUE = "value"
    PLACE = "place"
    GROUPING = "grouping"


class Noise(StrEnum):
    TYPOS = "typos"
    NO_ACCENTS = "no_accents"


@dataclass(frozen=True, slots=True)
class AmbiguousGold:
    """The Parser must return a non-empty `ambiguities[]`; `intent` is scored only when set."""

    reason: str
    intent: Intent | None = None


Gold = Question | AmbiguousGold


@dataclass(frozen=True, slots=True)
class VariantSpec:
    lang: str = "en"
    style: Style | None = None
    vague: Vague | None = None
    noise: Noise | None = None

    def __post_init__(self) -> None:
        if self.lang not in LANGUAGES:
            raise ValueError(f"unknown language {self.lang!r}")
        if self.lang == "en" and not (self.style or self.vague or self.noise):
            raise ValueError("the plain English variant is the concept itself")

    @property
    def key(self) -> str:
        parts = [self.lang, self.style, self.vague and f"vague_{self.vague}", self.noise]
        return "-".join(p for p in parts if p)

    @property
    def needs_llm(self) -> bool:
        return self.lang != "en" or self.style is not None or self.vague is not None


@dataclass(frozen=True, slots=True)
class Concept:
    id: str
    category: Category
    text: str
    gold: Gold
    variants: tuple[VariantSpec, ...] = ()

    def __post_init__(self) -> None:
        if isinstance(self.gold, Question) and self.gold.text != self.text:
            raise ValueError(f"{self.id}: the gold Question's text must be the concept's text")
        keys = [v.key for v in self.variants]
        if len(set(keys)) != len(keys):
            raise ValueError(f"{self.id}: duplicate variants")
        if any(v.vague for v in self.variants) and isinstance(self.gold, AmbiguousGold):
            raise ValueError(f"{self.id}: an ambiguous concept cannot be vaguised further")

    def variant_id(self, spec: VariantSpec) -> str:
        return f"{self.id}.{spec.key}"

    def gold_for(self, spec: VariantSpec, text: str) -> Gold:
        if spec.vague is not None:
            # Blurring together-vs-compared also blurs what kind of question it is.
            keeps_intent = isinstance(self.gold, Question) and spec.vague is not Vague.GROUPING
            intent = self.gold.intent if isinstance(self.gold, Question) and keeps_intent else None
            return AmbiguousGold(reason=f"vague {spec.vague}", intent=intent)
        if isinstance(self.gold, Question):
            return replace(self.gold, text=text)
        return self.gold


def clock(hh_mm: str) -> float:
    hours, minutes = hh_mm.split(":")
    return int(hours) * 3600.0 + int(minutes) * 60.0


def window(start: str, end: str) -> TimeWindow:
    return TimeWindow(clock(start), clock(end))


def kmh(value: float) -> float:
    return round(value / 3.6, 3)


def _q(text: str, intent: Intent, **fields: object) -> Question:
    return Question(text=text, intent=intent, **fields)  # type: ignore[arg-type]


def _closure(edge: str, w: TimeWindow) -> Intervention:
    return Intervention(InterventionType.EDGE_CLOSURE, EdgeTarget(edge), window=w)


def _lane_closure(edge: str, lane: int, w: TimeWindow) -> Intervention:
    return Intervention(InterventionType.LANE_CLOSURE, LaneTarget(edge, lane), window=w)


def _limit(
    edge: str, speed_kmh: float, w: TimeWindow | None = None, when: Condition | None = None
) -> Intervention:
    return Intervention(
        InterventionType.SPEED_LIMIT, EdgeTarget(edge), params={"speed": kmh(speed_kmh)},
        window=w, condition=when,
    )


def _signal(
    tls: str, program: str, w: TimeWindow | None = None, when: Condition | None = None
) -> Intervention:
    return Intervention(
        InterventionType.SIGNAL_PROGRAM, TlsTarget(tls), params={"program_id": program},
        window=w, condition=when,
    )


def _demand(factor: float, w: TimeWindow) -> Intervention:
    return Intervention(InterventionType.DEMAND_SCALE, None, params={"factor": factor}, window=w)


def _v(*keys: str) -> tuple[VariantSpec, ...]:
    """Variant specs from their keys, e.g. `_v("ca", "de-technical", "en-vague_time")`."""
    specs = []
    for key in keys:
        lang, *axes = key.split("-")
        fields: dict[str, object] = {}
        for axis in axes:
            if axis.startswith("vague_"):
                fields["vague"] = Vague(axis.removeprefix("vague_"))
            elif axis in {n.value for n in Noise}:
                fields["noise"] = Noise(axis)
            else:
                fields["style"] = Style(axis)
        specs.append(VariantSpec(lang, **fields))  # type: ignore[arg-type]
    return tuple(specs)


def _asked(
    concept_id: str, category: Category, text: str, intent: Intent,
    variants: tuple[VariantSpec, ...], **fields: object,
) -> Concept:
    """A concept whose gold is a `Question` on DEV-NET unless `network_ref` says otherwise."""
    fields.setdefault("network_ref", "DEV-NET")
    return Concept(concept_id, category, text, _q(text, intent, **fields), variants)


def _unclear(
    concept_id: str, category: Category, text: str, reason: str,
    variants: tuple[VariantSpec, ...], intent: Intent | None = None,
) -> Concept:
    return Concept(concept_id, category, text, AmbiguousGold(reason, intent), variants)


