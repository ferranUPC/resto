HELD_OUT_SHARE = 0.3


def _splits(concepts: tuple[Concept, ...]) -> dict[str, str]:
    """70/30 dev/held-out by concept, stratified by category so every category is in both: within
    a category, the concepts with the lowest crc32 of their id are held out."""
    splits = {}
    for category in Category:
        ids = sorted(
            (c.id for c in concepts if c.category is category),
            key=lambda concept_id: zlib.crc32(concept_id.encode()),
        )
        held_out = round(len(ids) * HELD_OUT_SHARE)
        splits.update({cid: "held_out" if i < held_out else "dev" for i, cid in enumerate(ids)})
    return splits


